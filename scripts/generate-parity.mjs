#!/usr/bin/env node
/**
 * Generates docs/PARITY.md from the sources: every bridge method used by the
 * JS client, whether each native bridge implements it, and every SDK event.
 * Status reflects source-level implementation only; device verification is
 * tracked separately in docs/STATUS.md.
 *
 * Usage: node scripts/generate-parity.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const walk = (dir, ext) =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? walk(p, ext) : p.endsWith(ext) ? [p] : [];
  });
const read = (files) => files.map((f) => readFileSync(f, 'utf8')).join('\n');

const js = read(walk(join(root, 'src'), '.ts'));
const kt = read(walk(join(root, 'android/src/main/java'), '.kt'));
const sw = read(walk(join(root, 'ios'), '.swift'));

const methods = [
  ...new Set(
    [...js.matchAll(/'((?:engine|channel|message|group|open|community|user|translate|tag|query|push)\.[A-Za-z]+)'/g)].map(
      (m) => m[1]
    )
  ),
].sort();
const has = (src, m) => new RegExp(`\\bon\\("${m.replace('.', '\\.')}"\\)`).test(src);

const AREAS = {
  engine: 'Lifecycle, settings, push & do-not-disturb',
  channel: 'Channels (direct, group, open, system, community)',
  message: 'Messages, receipts, media, metadata',
  group: 'Group channels',
  open: 'Open channels',
  community: 'Community channels',
  user: 'Users, friends, block list, presence',
  translate: 'Translation',
  tag: 'Channel tags',
  query: 'Paged queries',
  push: 'Push notifications (permission, token, taps)',
};

const kinds = [...js.matchAll(/new PagedQuery\(\s*this\.bridge,\s*'([A-Za-z]+)'/g)].map((m) => m[1]);
const events = [...js.matchAll(/'([A-Za-z]+Handler\.on[A-Za-z]+|Engine\.on[A-Za-z]+|Push\.on[A-Za-z]+)': \[\s*'([A-Za-z]+)'/g)].map((m) => [
  m[1],
  m[2],
]);

const cell = (ok) => (ok ? 'implemented' : 'unavailable upstream');
let out = `# Capability parity matrix\n\nGenerated by \`node scripts/generate-parity.mjs\` from the sources. Do not edit by hand.\n\n`;
out += `Pinned native SDKs: Android \`ai.nexconn.chat:chat:26.4.2\`, iOS \`NexconnChat/Chat 26.4.2\`.\n\n`;
out += `Statuses describe source-level implementation against the pinned SDK API. **No row is verified on a device or against the live service yet**; see docs/STATUS.md and docs/CLOUD_TEST_RUNBOOK.md. "unavailable upstream" means the vendor SDK for that platform has no equivalent API, and the bridge rejects the call with \`unsupported\`.\n\n`;
out += `Totals: ${methods.length} bridge methods, ${kinds.length} paged query kinds, ${events.length} SDK event types.\n\n`;
for (const [prefix, title] of Object.entries(AREAS)) {
  const rows = methods.filter((m) => m.startsWith(`${prefix}.`));
  if (!rows.length) continue;
  out += `## ${title}\n\n| Bridge method | Android | iOS |\n| --- | --- | --- |\n`;
  for (const m of rows) out += `| \`${m}\` | ${cell(has(kt, m))} | ${cell(has(sw, m))} |\n`;
  out += '\n';
}
out += `## Paged query kinds\n\n| Kind | Android | iOS |\n| --- | --- | --- |\n`;
for (const k of kinds) {
  out += `| \`${k}\` | ${cell(kt.includes(`"${k}" ->`))} | ${cell(sw.includes(`case "${k}":`))} |\n`;
}
out += `\n## SDK events\n\n| Native handler callback | JS event | Android | iOS |\n| --- | --- | --- | --- |\n`;
for (const [type, name] of events) {
  out += `| \`${type}\` | \`${name}\` | ${cell(kt.includes(`"${type}"`))} | ${cell(sw.includes(`"${type}"`))} |\n`;
}
out += `\n## Not exposed (by design or pending)\n\n`;
out += `- Calls (RTC) — separate product, out of scope for this Chat SDK.\n`;
out += `- Chat UI kit — this package is headless; React hooks are provided instead.\n`;
out += `- Android \`UserModule.deleteFriends\` — duplicate of \`removeFriends\` in the Android SDK; iOS has only \`removeFriends\`.\n`;
out += `- iOS \`CommunitySearchMessagesByKeywordQuery\` / \`CommunitySearchMessagesByUserQuery\` — no public factory found in the 26.4.2 interface; use \`searchMessagesByUser\` with \`subChannelIds\`.\n`;
out += `- Android \`Message.restorePreviewDownloadedLocalPath\`, \`Message.createForPreview\`, \`BaseChannel.setEditedMessageDraft\` (local property setter) — UI-preview helpers not needed through the bridge.\n`;
out += `- \`push.requestPermission\` on Android is implemented in JS (\`PermissionsAndroid\`, Android 13+), not natively.\n`;
out += `- Custom message types — supported through 16 plain + 16 media generic slots per platform (see docs/API.md).\n`;
writeFileSync(join(root, 'docs/PARITY.md'), out);
console.log(`docs/PARITY.md: ${methods.length} methods, ${kinds.length} queries, ${events.length} events`);
